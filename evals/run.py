    sid = str(uuid.uuid4())
    wx = patch_metric_series(make_weather(), "wind_gusts_10m", 12)
    g = build_graph(llm, SOPS_DIR, geocode=geo, fetch_forecast_fn=fake_fetch_factory(wx))
    await run_turn(g, sid, "cycling in Bhopal today")
    res = await run_turn(g, sid, "what about this evening instead?")
