class Results:
    def __init__(self):
        self.lines = ["# Eval Results\n", f"Generated by evals/run.py\n"]

    def add(self, name: str, criteria: str, status: str, notes: str = ""):
        self.lines.append(f"## {name}\n")
        self.lines.append(f"- **Checks:** {criteria}\n")
        self.lines.append(f"- **Result:** {status}\n")
        if notes:
            self.lines.append(f"- **Notes:** {notes}\n")
        self.lines.append("\n")

    def write(self):
        RESULTS_PATH.write_text("".join(self.lines), encoding="utf-8")


def fake_geocode_factory(mapping: dict[str, GeocodeResult | None]):
    async def geocode(name, country_code=None, count=5, client=None):
        key = name.lower().split(",")[0].strip()
        for k, v in mapping.items():
            if k.lower() in key or key in k.lower():
                return [v] if v else []
        if "bhopal" in key:
            return [
                GeocodeResult(
                    name="Bhopal",
                    latitude=23.26,
                    longitude=77.4,
                    country_code="IN",
                    admin1="Madhya Pradesh",
                )
            ]
        if "zzxqvk" in key.lower():
            return []
        if "kashmir" in key:
            return [GeocodeResult(name="Srinagar", latitude=34.08, longitude=74.79, country_code="IN", admin1="Jammu and Kashmir")]
        if "kanyakumari" in key:
            return [GeocodeResult(name="Kanyakumari", latitude=8.08, longitude=77.57, country_code="IN", admin1="Tamil Nadu")]
        return [
            GeocodeResult(
                name=name,
                latitude=23.26,
                longitude=77.4,
                country_code="IN",
                admin1="Test",
            )
        ]

    return geocode


def fake_fetch_factory(payload: dict):
    async def fetch(lat, lon, hourly_vars, forecast_days=3, client=None):
        # Filter hourly keys to requested vars + time
        hourly = {"time": payload["hourly"]["time"]}
        for v in hourly_vars:
            if v in payload["hourly"]:
                hourly[v] = payload["hourly"][v]
        slim = {**payload, "hourly": hourly}
        return ForecastPayload.model_validate(slim)

    return fetch


def fired_ids(trace: dict) -> set[str]:
    return {f["id"] for f in trace.get("fired") or []}


def reply_text(result: dict) -> str:
    return result.get("reply") or ""


async def main():
    load_dotenv()
    r = Results()
    api_key = os.getenv("OPENAI_API_KEY")
    if not api_key:
        r.add("Setup", "OPENAI_API_KEY present", "SKIPPED", "No API key")
        r.write()
        print("No OPENAI_API_KEY — wrote SKIPPED results")
        return

    llm = ChatOpenAI(model=os.getenv("MODEL", "gpt-4o-mini"), temperature=0)

    async def run_case(name, question, geocode, fetch, session=None, sops_dir=SOPS_DIR):
        g = build_graph(llm, sops_dir, geocode=geocode, fetch_forecast_fn=fetch)
        sid = session or str(uuid.uuid4())
        return await run_turn(g, sid, question)

