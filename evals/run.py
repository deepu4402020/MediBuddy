    r.add("8 No trigger", "no_trigger lists checked SOPs", "PASS" if ok else "FAIL", tr.get("no_sop_reason", ""))

    # 9 Weather down
    async def boom(*a, **k):
        raise RuntimeError("api down")

    res = await run_case("t9", "cycling in Bhopal", geo, boom)
    tr = res.get("trace") or {}
