    ok = tr.get("no_sop_reason") == "no_topic" and tr.get("composer_calls", 0) == 0
    r.add("7 No topic", "no_topic, zero composer calls", "PASS" if ok else "FAIL", str(tr))

    # 8 No trigger mild + cycling
    wx = make_weather()
    res = await run_case("t8", "cycling in Bhopal today", geo, fake_fetch_factory(wx))
    tr = res.get("trace") or {}
