    u = tr.get("understand") or {}
    ok = tr.get("no_sop_reason") != "location_unresolved" and (u.get("when") or {}).get("part") in ("evening", "all_day", "night")
    r.add("14 Session evening", "location inherited, evening window", "PASS" if ok else "FAIL", str(u.get("when")))

